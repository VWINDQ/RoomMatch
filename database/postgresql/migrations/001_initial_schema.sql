CREATE TABLE FRIEND_CONNECTION (
  connection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id BIGINT NOT NULL REFERENCES USER(user_id) ON DELETE CASCADE,
  recipient_id BIGINT NOT NULL REFERENCES USER(user_id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  responded_at TIMESTAMPTZ,
  CHECK (sender_id <> recipient_id),
  CHECK ((status = 'pending' AND responded_at IS NULL) OR (status <> 'pending' AND responded_at IS NOT NULL))
);
CREATE UNIQUE INDEX friend_connection_pair ON FRIEND_CONNECTION (LEAST(sender_id, recipient_id), GREATEST(sender_id, recipient_id));
CREATE INDEX friend_connection_recipient ON FRIEND_CONNECTION(recipient_id, status);
CREATE INDEX friend_connection_sender ON FRIEND_CONNECTION(sender_id, status);
