-- Lock the room before checking occupancy. All API paths take locks in the same
-- order (room, then request/member), so concurrent approvals cannot overbook.
CREATE FUNCTION room_request_validate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target ROOM%ROWTYPE; occupancy BIGINT;
BEGIN
  SELECT * INTO target FROM ROOM WHERE room_id = NEW.room_id FOR UPDATE;
  IF NOT FOUND THEN RETURN NEW; END IF; -- The foreign key reports missing rooms.
  SELECT 1 + COUNT(*) INTO occupancy FROM ROOM_MEMBER WHERE room_id = NEW.room_id AND status = 'approved';
  IF TG_OP = 'INSERT' THEN
    IF target.status <> 'available' THEN RAISE EXCEPTION 'room is not available for requests'; END IF;
    IF target.owner_id = NEW.user_id THEN RAISE EXCEPTION 'room owner cannot request own room'; END IF;
    IF EXISTS (SELECT 1 FROM ROOM_MEMBER WHERE room_id = NEW.room_id AND user_id = NEW.user_id AND status = 'approved') THEN
      RAISE EXCEPTION 'approved member cannot request the same room';
    END IF;
    IF occupancy >= target.capacity THEN RAISE EXCEPTION 'room capacity reached'; END IF;
  ELSIF NEW.status <> OLD.status THEN
    IF OLD.status <> 'pending' THEN RAISE EXCEPTION 'request decision is final'; END IF;
    IF NEW.status = 'approved' THEN
      IF target.status = 'inactive' THEN RAISE EXCEPTION 'inactive room request cannot be approved'; END IF;
      IF EXISTS (SELECT 1 FROM ROOM_MEMBER WHERE room_id = NEW.room_id AND user_id = NEW.user_id AND status = 'approved') THEN
        RAISE EXCEPTION 'user is already an approved room member';
      END IF;
      IF occupancy >= target.capacity THEN RAISE EXCEPTION 'room capacity reached'; END IF;
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_room_request_validate_insert BEFORE INSERT ON ROOM_REQUEST FOR EACH ROW EXECUTE FUNCTION room_request_validate();
CREATE TRIGGER trg_room_request_validate_transition BEFORE UPDATE OF status ON ROOM_REQUEST FOR EACH ROW EXECUTE FUNCTION room_request_validate();

CREATE FUNCTION room_member_validate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target ROOM%ROWTYPE; occupancy BIGINT;
BEGIN
  SELECT * INTO target FROM ROOM WHERE room_id = NEW.room_id FOR UPDATE;
  IF target.owner_id = NEW.user_id THEN RAISE EXCEPTION 'room owner is not stored as a room member'; END IF;
  IF NEW.status = 'approved' THEN
    IF NOT EXISTS (SELECT 1 FROM ROOM_REQUEST WHERE room_id = NEW.room_id AND user_id = NEW.user_id AND status = 'approved') THEN
      RAISE EXCEPTION 'approved membership requires an approved request';
    END IF;
    SELECT 1 + COUNT(*) INTO occupancy FROM ROOM_MEMBER WHERE room_id = NEW.room_id AND status = 'approved' AND user_id <> NEW.user_id;
    IF occupancy >= target.capacity THEN RAISE EXCEPTION 'room capacity reached'; END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_room_member_validate_insert BEFORE INSERT ON ROOM_MEMBER FOR EACH ROW EXECUTE FUNCTION room_member_validate();
CREATE TRIGGER trg_room_member_validate_reactivation BEFORE UPDATE OF status ON ROOM_MEMBER FOR EACH ROW WHEN (OLD.status <> 'approved' AND NEW.status = 'approved') EXECUTE FUNCTION room_member_validate();

CREATE FUNCTION room_member_refresh_status() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target_id BIGINT;
BEGIN
  IF TG_OP = 'DELETE' THEN target_id := OLD.room_id; ELSE target_id := NEW.room_id; END IF;
  UPDATE ROOM SET status = CASE WHEN 1 + (SELECT COUNT(*) FROM ROOM_MEMBER WHERE room_id = target_id AND status = 'approved') >= capacity THEN 'full' ELSE 'available' END
    WHERE room_id = target_id AND status <> 'inactive';
  RETURN NULL;
END $$;
CREATE TRIGGER trg_room_member_mark_full_insert AFTER INSERT ON ROOM_MEMBER FOR EACH ROW EXECUTE FUNCTION room_member_refresh_status();
CREATE TRIGGER trg_room_member_refresh_status_update AFTER UPDATE OF status ON ROOM_MEMBER FOR EACH ROW EXECUTE FUNCTION room_member_refresh_status();
CREATE TRIGGER trg_room_member_refresh_status_delete AFTER DELETE ON ROOM_MEMBER FOR EACH ROW EXECUTE FUNCTION room_member_refresh_status();

CREATE FUNCTION room_capacity_validate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE occupancy BIGINT;
BEGIN
  SELECT 1 + COUNT(*) INTO occupancy FROM ROOM_MEMBER WHERE room_id = NEW.room_id AND status = 'approved';
  IF NEW.capacity < occupancy THEN RAISE EXCEPTION 'capacity cannot be lower than current occupancy'; END IF;
  IF NEW.status <> 'inactive' THEN NEW.status := CASE WHEN occupancy >= NEW.capacity THEN 'full' ELSE 'available' END; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_room_capacity_validate BEFORE UPDATE OF capacity ON ROOM FOR EACH ROW EXECUTE FUNCTION room_capacity_validate();

CREATE FUNCTION matches_validate() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.initiator_user_id = NEW.completer_user_id THEN RAISE EXCEPTION 'cannot create a self-match'; END IF;
  IF NOT EXISTS (SELECT 1 FROM ROOM WHERE room_id = NEW.room_id AND owner_id = NEW.initiator_user_id) THEN RAISE EXCEPTION 'match initiator must own the room'; END IF;
  IF NOT EXISTS (SELECT 1 FROM ROOM_MEMBER WHERE room_id = NEW.room_id AND user_id = NEW.completer_user_id AND status = 'approved') THEN RAISE EXCEPTION 'match completer must be an approved member'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_matches_validate BEFORE INSERT OR UPDATE ON MATCHES FOR EACH ROW EXECUTE FUNCTION matches_validate();

CREATE FUNCTION friend_connection_validate() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.sender_id <> OLD.sender_id OR NEW.recipient_id <> OLD.recipient_id OR OLD.status <> 'pending' OR NEW.status NOT IN ('accepted', 'declined', 'cancelled') THEN
    RAISE EXCEPTION 'Invalid friend connection transition';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER friend_connection_transition BEFORE UPDATE ON FRIEND_CONNECTION FOR EACH ROW EXECUTE FUNCTION friend_connection_validate();

CREATE FUNCTION user_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.updated_at = OLD.updated_at THEN NEW.updated_at := clock_timestamp(); END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_user_touch_updated_at BEFORE UPDATE ON USER FOR EACH ROW EXECUTE FUNCTION user_touch_updated_at();
